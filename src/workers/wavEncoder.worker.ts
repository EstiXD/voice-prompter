// Worker: PCM Float32 (mono o multi-canal, ya mezclado a mono por el llamador)
// → WAV PCM 16-bit. Corre fuera del hilo principal para no congelar la UI.

export type WavEncodeRequest = { samples: Float32Array; sampleRate: number };
export type WavEncodeResponse = { wav: ArrayBuffer };

function encodeWav(samples: Float32Array, sampleRate: number): ArrayBuffer {
  const bytesPerSample = 2;
  const buffer = new ArrayBuffer(44 + samples.length * bytesPerSample);
  const view = new DataView(buffer);
  const writeStr = (offset: number, s: string) => {
    for (let i = 0; i < s.length; i++) view.setUint8(offset + i, s.charCodeAt(i));
  };
  writeStr(0, "RIFF");
  view.setUint32(4, 36 + samples.length * bytesPerSample, true);
  writeStr(8, "WAVE");
  writeStr(12, "fmt ");
  view.setUint32(16, 16, true); // tamaño del chunk fmt
  view.setUint16(20, 1, true); // PCM
  view.setUint16(22, 1, true); // mono
  view.setUint32(24, sampleRate, true);
  view.setUint32(28, sampleRate * bytesPerSample, true);
  view.setUint16(32, bytesPerSample, true);
  view.setUint16(34, 16, true);
  writeStr(36, "data");
  view.setUint32(40, samples.length * bytesPerSample, true);
  let offset = 44;
  for (let i = 0; i < samples.length; i++, offset += 2) {
    const s = Math.max(-1, Math.min(1, samples[i]));
    view.setInt16(offset, s < 0 ? s * 0x8000 : s * 0x7fff, true);
  }
  return buffer;
}

self.onmessage = (e: MessageEvent<WavEncodeRequest>) => {
  const { samples, sampleRate } = e.data;
  const wav = encodeWav(samples, sampleRate);
  const res: WavEncodeResponse = { wav };
  (self as unknown as Worker).postMessage(res, [wav]);
};
